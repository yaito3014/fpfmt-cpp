"""Generates fpfmt as a single header from the headers under include/.

Starting from include/yk/fpfmt.hpp, every #include <yk/fpfmt/...> is replaced
by the file's contents, once per file, in the order they are first reached.
Unconditional standard headers are kept at their first occurrence only;
conditional ones (inside #if, such as <intrin.h>) are kept where they are.
The parts keep their include guards, so the single header and the split
headers can still be included together. The license comment at the top of
each part, which refers to the notice in yk/fpfmt.hpp, is dropped, since that
notice opens the generated file.

This is a textual concatenation on purpose, not a preprocessor run: a
preprocessor would resolve #if (such as the unsigned __int128 check in
detail/config.hpp) for the machine doing the bundling, and inline its standard
library.

usage: python3 tools/amalgamate.py [OUTPUT]
       (OUTPUT defaults to single_include/yk/fpfmt.hpp, which git ignores)
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
INCLUDE = os.path.join(ROOT, "include")
ENTRY = "yk/fpfmt.hpp"
DEFAULT_OUTPUT = os.path.join(ROOT, "single_include", "yk", "fpfmt.hpp")

PROJECT_INCLUDE = re.compile(r"#include <(yk/fpfmt(?:/[^>]+)?\.hpp)>\s*$")
SYSTEM_INCLUDE = re.compile(r"#include <[^>]+>\s*$")

HEADER = """\
// fpfmt-cpp: single-header form.
// Generated by tools/amalgamate.py from the headers under include/; do not edit.

"""


def amalgamate() -> str:
    seen_files: set[str] = set()
    seen_system: set[str] = set()
    out: list[str] = []

    def inline(path: str) -> None:
        if path in seen_files:
            return
        seen_files.add(path)
        depth = 0
        in_leading_comment = path != ENTRY
        with open(os.path.join(INCLUDE, path)) as f:
            for line in f:
                stripped = line.strip()
                if in_leading_comment:
                    if stripped.startswith("//") or not stripped:
                        continue
                    in_leading_comment = False
                if stripped.startswith("#if"):
                    depth += 1
                elif stripped.startswith("#endif"):
                    depth -= 1
                match = PROJECT_INCLUDE.match(stripped)
                if match:
                    # an include inside a conditional would need the condition kept
                    assert depth == 1, f"{path}: conditional #include of a part"
                    inline(match.group(1))
                    continue
                if SYSTEM_INCLUDE.match(stripped) and depth == 1:
                    if stripped in seen_system:
                        continue
                    seen_system.add(stripped)
                out.append(line)
        out.append("\n")

    inline(ENTRY)
    text = HEADER + "".join(out)
    # the removed includes leave runs of blank lines
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.rstrip("\n") + "\n"


def main() -> int:
    if len(sys.argv) > 2 or sys.argv[1:2] in (["-h"], ["--help"]):
        print(__doc__, file=sys.stderr)
        return 2
    output = sys.argv[1] if len(sys.argv) == 2 else DEFAULT_OUTPUT
    text = amalgamate()
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    with open(output, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
